"""Regenerates every cost table and inline figure in the book from data/prices.toml.

Each module in costs/ (except those starting with an underscore) defines
    ID: str
    build(P, H) -> {"tables": {name: markdown}, "vars": {dotted.key: str}}
Tables are written to _generated/costs/<ID>-<name>.md and included by chapters.
Vars are merged into _variables.yml and used in prose as {{< var <ID>.<key> >}}.

  python3 tools/costgen.py          write the outputs
  python3 tools/costgen.py --check  fail if the committed outputs are stale

Fails when it finds no scenarios: a check that examined nothing did not pass.
"""

from __future__ import annotations

import importlib.util
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "costs"))
import _lib  # noqa: E402

OUT = ROOT / "_generated" / "costs"
VARS = ROOT / "_variables.yml"


def yaml_scalar(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def to_yaml(tree: dict, indent: int = 0) -> str:
    lines = []
    for k in sorted(tree):
        v = tree[k]
        if isinstance(v, dict):
            lines.append(" " * indent + f"{k}:")
            lines.append(to_yaml(v, indent + 2))
        else:
            lines.append(" " * indent + f"{k}: {yaml_scalar(v)}")
    return "\n".join(lines)


def nest(flat: dict[str, str]) -> dict:
    tree: dict = {}
    for dotted, v in flat.items():
        node = tree
        *parents, leaf = dotted.split(".")
        for p in parents:
            node = node.setdefault(p, {})
            if not isinstance(node, dict):
                raise ValueError(f"var {dotted} collides with a scalar")
        if leaf in node:
            raise ValueError(f"duplicate var {dotted}")
        node[leaf] = v
    return tree


def main() -> int:
    check = "--check" in sys.argv
    modules = sorted(
        p for p in (ROOT / "costs").glob("*.py") if not p.name.startswith("_")
    )
    if not modules:
        print("costgen: 0 scenarios found. Nothing generated is a failure.")
        return 1

    P, H = _lib.prices(), _lib.hardware()
    files: dict[Path, str] = {}
    flat: dict[str, str] = {"prices.as_of": P.raw["meta"]["as_of"]}
    n_tables = 0
    for path in modules:
        spec = importlib.util.spec_from_file_location(path.stem, path)
        mod = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(mod)
        result = mod.build(P, H)
        for name, md in result["tables"].items():
            files[OUT / f"{mod.ID}-{name}.md"] = md
            n_tables += 1
        for k, v in result["vars"].items():
            flat[f"{mod.ID}.{k}"] = str(v)
    files[VARS] = (
        "# Generated by tools/costgen.py from data/prices.toml. Do not edit.\n"
        + to_yaml(nest(flat))
        + "\n"
    )

    if check:
        stale = [
            p
            for p, text in files.items()
            if not p.exists() or p.read_text(encoding="utf-8") != text
        ]
        expected = set(files)
        orphans = [p for p in OUT.glob("*.md") if p not in expected]
        if stale or orphans:
            for p in stale:
                print(f"costgen: stale {p.relative_to(ROOT)}")
            for p in orphans:
                print(f"costgen: orphan {p.relative_to(ROOT)}")
            print("costgen: run `make costs` and commit the result.")
            return 1
        print(
            f"costgen: {len(modules)} scenarios, {n_tables} tables, {len(flat)} vars checked, all current."
        )
        return 0

    OUT.mkdir(parents=True, exist_ok=True)
    for p in OUT.glob("*.md"):
        if p not in files:
            p.unlink()
    for p, text in files.items():
        p.write_text(text, encoding="utf-8")
    print(
        f"costgen: {len(modules)} scenarios, {n_tables} tables, {len(flat)} vars written; "
        f"{len(P.used)} price entries used."
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
